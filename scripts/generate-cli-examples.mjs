/**
 * Build packages/cli/src/examples.generated.ts from docs demo snippets.
 * Rewrites @/components/* imports → @joyui/react (composer → /composer).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const codesPath = path.join(
  root,
  "apps/docs/components/demos/component-doc-codes.ts",
);
const outPath = path.join(root, "packages/cli/src/examples.generated.ts");

function loadCodes() {
  if (!fs.existsSync(codesPath)) return {};
  const src = fs.readFileSync(codesPath, "utf8");
  const out = {};
  const re = /"([^"]+)":\s*"((?:\\.|[^"\\])*)"/g;
  let m;
  while ((m = re.exec(src))) {
    try {
      out[m[1]] = JSON.parse(`"${m[2]}"`);
    } catch {
      // skip malformed
    }
  }
  return out;
}

function rewriteImports(code) {
  return code
    .replace(
      /from\s+["']@\/components\/application\/composer(?:-loader|-panel)?\/[^"']+["']/g,
      'from "@joyui/react/composer"',
    )
    .replace(/from\s+["']@\/components\/[^"']+["']/g, 'from "@joyui/react"')
    .replace(/from\s+["']@\/utils\/[^"']+["']/g, 'from "@joyui/react"')
    .replace(/from\s+["']@\/lib\/[^"']+["']/g, 'from "@joyui/react"');
}

const codes = loadCodes();
const examples = {};
for (const [name, code] of Object.entries(codes)) {
  if (typeof code !== "string" || !code.trim()) continue;
  examples[name] = rewriteImports(code).trim() + "\n";
}

const body = `/** AUTO-GENERATED by scripts/generate-cli-examples.mjs — do not edit. */
export const GENERATED_EXAMPLES: Record<string, string> = ${JSON.stringify(examples, null, 2)};
`;

fs.writeFileSync(outPath, body);
console.log(
  `Generated ${Object.keys(examples).length} CLI examples → ${outPath}`,
);
