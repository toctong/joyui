const SLUG_ALIASES: Record<string, string> = {};

export function resolveDocsComponent(
  slugs: string[] | undefined,
): string | undefined {
  const last = slugs?.at(-1);
  if (!last) return undefined;
  const name = SLUG_ALIASES[last] ?? last;
  return REGISTRY_NAMES.has(last) || REGISTRY_NAMES.has(name) ? name : undefined;
}
